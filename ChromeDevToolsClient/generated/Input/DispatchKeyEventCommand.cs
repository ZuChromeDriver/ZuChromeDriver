namespace Zu.ChromeDevTools.Input
{
    using System.Text.Json.Serialization;

    /// <summary>
    /// Dispatches a key event to the page.
    /// </summary>
    public sealed class DispatchKeyEventCommand : ICommand
    {
        private const string ChromeRemoteInterface_CommandName = "Input.dispatchKeyEvent";
        
        [JsonIgnore]
        public string CommandName
        {
            get { return ChromeRemoteInterface_CommandName; }
        }

        /// <summary>
        /// Type of the key event.
        /// </summary>
        [JsonPropertyName("type")]
        public string Type
        {
            get;
            set;
        }
        /// <summary>
        /// Bit field representing pressed modifier keys. Alt=1, Ctrl=2, Meta/Command=4, Shift=8
        /// (default: 0).
        /// </summary>
        [JsonPropertyName("modifiers")]
        [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingDefault)]
        public long? Modifiers
        {
            get;
            set;
        }
        /// <summary>
        /// Time at which the event occurred.
        /// </summary>
        [JsonPropertyName("timestamp")]
        [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingDefault)]
        public double? Timestamp
        {
            get;
            set;
        }
        /// <summary>
        /// Text as generated by processing a virtual key code with a keyboard layout. Not needed for
        /// for `keyUp` and `rawKeyDown` events (default: "")
        /// </summary>
        [JsonPropertyName("text")]
        [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingDefault)]
        public string Text
        {
            get;
            set;
        }
        /// <summary>
        /// Text that would have been generated by the keyboard if no modifiers were pressed (except for
        /// shift). Useful for shortcut (accelerator) key handling (default: "").
        /// </summary>
        [JsonPropertyName("unmodifiedText")]
        [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingDefault)]
        public string UnmodifiedText
        {
            get;
            set;
        }
        /// <summary>
        /// Unique key identifier (e.g., 'U+0041') (default: "").
        /// </summary>
        [JsonPropertyName("keyIdentifier")]
        [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingDefault)]
        public string KeyIdentifier
        {
            get;
            set;
        }
        /// <summary>
        /// Unique DOM defined string value for each physical key (e.g., 'KeyA') (default: "").
        /// </summary>
        [JsonPropertyName("code")]
        [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingDefault)]
        public string Code
        {
            get;
            set;
        }
        /// <summary>
        /// Unique DOM defined string value describing the meaning of the key in the context of active
        /// modifiers, keyboard layout, etc (e.g., 'AltGr') (default: "").
        /// </summary>
        [JsonPropertyName("key")]
        [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingDefault)]
        public string Key
        {
            get;
            set;
        }
        /// <summary>
        /// Windows virtual key code (default: 0).
        /// </summary>
        [JsonPropertyName("windowsVirtualKeyCode")]
        [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingDefault)]
        public long? WindowsVirtualKeyCode
        {
            get;
            set;
        }
        /// <summary>
        /// Native virtual key code (default: 0).
        /// </summary>
        [JsonPropertyName("nativeVirtualKeyCode")]
        [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingDefault)]
        public long? NativeVirtualKeyCode
        {
            get;
            set;
        }
        /// <summary>
        /// Whether the event was generated from auto repeat (default: false).
        /// </summary>
        [JsonPropertyName("autoRepeat")]
        [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingDefault)]
        public bool? AutoRepeat
        {
            get;
            set;
        }
        /// <summary>
        /// Whether the event was generated from the keypad (default: false).
        /// </summary>
        [JsonPropertyName("isKeypad")]
        [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingDefault)]
        public bool? IsKeypad
        {
            get;
            set;
        }
        /// <summary>
        /// Whether the event was a system key event (default: false).
        /// </summary>
        [JsonPropertyName("isSystemKey")]
        [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingDefault)]
        public bool? IsSystemKey
        {
            get;
            set;
        }
        /// <summary>
        /// Whether the event was from the left or right side of the keyboard. 1=Left, 2=Right (default:
        /// 0).
        /// </summary>
        [JsonPropertyName("location")]
        [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingDefault)]
        public long? Location
        {
            get;
            set;
        }
        /// <summary>
        /// Editing commands to send with the key event (e.g., 'selectAll') (default: []).
        /// These are related to but not equal the command names used in `document.execCommand` and NSStandardKeyBindingResponding.
        /// See https://source.chromium.org/chromium/chromium/src/+/main:third_party/blink/renderer/core/editing/commands/editor_command_names.h for valid command names.
        /// </summary>
        [JsonPropertyName("commands")]
        [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingDefault)]
        public string[] Commands
        {
            get;
            set;
        }
    }

    public sealed class DispatchKeyEventCommandResponse : ICommandResponse<DispatchKeyEventCommand>
    {
    }
}